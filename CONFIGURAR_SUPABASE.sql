begin;
create table if not exists public.programaciones_compartidas (
 id bigint generated by default as identity primary key,
 fecha date not null,
 turno text not null,
 datos jsonb not null,
 actualizado_en timestamptz not null default now(),
 unique(fecha, turno)
);
-- Si existen varias programaciones privadas para la misma fecha/turno, detener
-- la migración para evitar elegir o sobrescribir datos sin autorización.
do $$ begin
 if exists (select 1 from public.programaciones_diarias group by fecha, turno having count(*) > 1) then
 raise exception 'Hay fechas y turnos duplicados entre usuarios. Resolver antes de migrar.';
 end if;
end $$;
insert into public.programaciones_compartidas(fecha,turno,datos,actualizado_en)
select fecha,turno,datos,coalesce(actualizado_en,now()) from public.programaciones_diarias
on conflict(fecha,turno) do nothing;
alter table public.programaciones_compartidas enable row level security;
grant select, insert, update, delete on public.programaciones_compartidas to anon, authenticated;
grant usage, select on sequence public.programaciones_compartidas_id_seq to anon, authenticated;
drop policy if exists acceso_compartido on public.programaciones_compartidas;
create policy acceso_compartido on public.programaciones_compartidas for all to anon, authenticated using (true) with check (true);
commit;
